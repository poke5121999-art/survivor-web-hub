// Copies the view and sound layer of Blockade Z into js/bz/ with a few anchored patches. js/bz/ is generated:
// never edit it by hand, change the patch list here and rerun. A patch whose anchor is missing stops the tool.
// Usage: node games/ai-sinh-ton/tools/port-bz.mjs [--check]   (--check fails when js/bz/ differs from a fresh port)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(HERE, '../../blockade-z/js');
const OUT = path.resolve(HERE, '../js/bz');
const HEAD = '// GENERATED by tools/port-bz.mjs from games/blockade-z/js/%s. Do not edit: change the tool and rerun.\n';

// load order matters: it is the order index.html lists them in
export const FILES = ['boot.js', 'core.js', 'i18n.js', 'lang-vi.js', 'art.js', 'audio.js', 'fx.js', 'zombies.js', 'zkinds.js', 'bosses.js',
  'boss-dragon.js', 'boss-pharaoh.js', 'boss-vampire.js', 'boss-alien.js', 'boss-ufo.js', 'boss-guardian.js', 'weapons.js', 'heroes.js', 'castanim.js', 'post.js'];

const PATCHES = {
  'boot.js': [["'../vendor/three.module.min.js'", "'../../vendor/three.module.min.js'"]],
  // own storage keys: both games live on one origin and must not read or write each other's settings
  'core.js': [["'blockadez.settings.v1'", "'aisinhton.bz.settings.v1'"], ["'blockadez.best.v1'", "'aisinhton.bz.best.v1'"]],
  // the game is Vietnamese only, and the voxel layer (js/vox, needs games/voxel-lab) is not ported
  'i18n.js': [["BZ.lang = known(BZ.params.lang) ? BZ.params.lang : known(saved) ? saved : 'en';", "BZ.lang = 'vi'; BZ.vox = { on: false };"],
    ["let saved = null; try { saved = localStorage.getItem(KEY); } catch {}", ''],
    ["try { localStorage.setItem(KEY, l); } catch {}", '']],
};

export function port() {
  const out = {};
  for (const f of FILES) {
    let s = fs.readFileSync(path.join(SRC, f), 'utf8');
    for (const [a, b] of PATCHES[f] || []) {
      const n = s.split(a).length - 1;
      if (n !== 1) throw new Error(`port-bz: anchor found ${n} times in ${f}: ${a}`);
      s = s.replace(a, b);
    }
    out[f] = HEAD.replace('%s', f) + s;
  }
  return out;
}

const fresh = port();
if (process.argv.includes('--check')) {
  const bad = Object.keys(fresh).filter((f) => { try { return fs.readFileSync(path.join(OUT, f), 'utf8') !== fresh[f]; } catch (e) { return true; } });
  console.log(bad.length ? 'port-bz: js/bz differs from a fresh port: ' + bad.join(', ') : `port-bz: GATE PASS (${FILES.length} files identical)`);
  process.exit(bad.length ? 1 : 0);
}
fs.mkdirSync(OUT, { recursive: true });
for (const f of Object.keys(fresh)) fs.writeFileSync(path.join(OUT, f), fresh[f]);
console.log(`port-bz: wrote ${FILES.length} files to js/bz`);
