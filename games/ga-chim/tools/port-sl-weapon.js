// Generates js/sl/weapon-sl.js from the beautified Saltline bundle: rifle geometry, gloved hands,
// markings atlas, reflex sight, gun materials and the viewmodel controller (springs, poses, reload, flash).
// Saltline is by Felix Rieseberg (claude.ai artifact BGY1SztrAYcJQHSsnHHGmp); this keeps its code and
// numbers, renames minified three.js aliases, and rebrands the engraved text.
// Usage: node tools/port-sl-weapon.js [D:/ref-saltline-gh/work/game.pretty.js]
'use strict';
const fs = require('fs');
const path = require('path');
const SRC = process.argv[2] || 'D:/ref-saltline-gh/work/game.pretty.js';
const OUT = path.join(__dirname, '..', 'js', 'sl', 'weapon-sl.js');
const lines = fs.readFileSync(SRC, 'utf8').split('\n').map((l) => l.replace(/\r$/, ''));
const slice = (a, b) => lines.slice(a - 1, b).join('\n');

// three.js export table at the top of the bundle: "Name: () => alias"
const alias = new Map();
for (const l of lines.slice(0, 800)) { const m = l.match(/^\s+([A-Za-z0-9_]+): \(\) => ([A-Za-z0-9_$]+),?$/); if (m) alias.set(m[2], m[1]); }

const utils = slice(24100, 24263) + '\n' + slice(24289, 24307);
let body = slice(45296, 47497);
// free identifiers of the extracted code (acorn walk, scope-insensitive) that the three.js table names
const acorn = require(process.env.ACORN || 'C:/Users/tamph/AppData/Roaming/npm/node_modules/@google/gemini-cli/node_modules/acorn');
function freeIds(src) {
  const ast = acorn.parse('(function(){\n' + src + '\n})', { ecmaVersion: 2022 });
  const decl = new Set(), refs = new Set();
  const pat = (p) => { if (!p) return; if (p.type === 'Identifier') decl.add(p.name); else if (p.type === 'ObjectPattern') p.properties.forEach((q) => pat(q.value || q.argument)); else if (p.type === 'ArrayPattern') p.elements.forEach(pat); else if (p.type === 'AssignmentPattern') pat(p.left); else if (p.type === 'RestElement') pat(p.argument); };
  const walk = (n, parent, key) => {
    if (!n || typeof n.type !== 'string') return;
    if (n.type === 'VariableDeclarator') pat(n.id);
    else if (/Function/.test(n.type)) { if (n.id) decl.add(n.id.name); n.params.forEach(pat); }
    else if (/^Class/.test(n.type) && n.id) decl.add(n.id.name);
    else if (n.type === 'CatchClause') pat(n.param);
    else if (n.type === 'Identifier') {
      const isProp = parent && ((parent.type === 'MemberExpression' && key === 'property' && !parent.computed) || (/Property|MethodDefinition/.test(parent.type) && key === 'key' && !parent.computed && !parent.shorthand));
      if (!isProp) refs.add(n.name);
    }
    for (const k of Object.keys(n)) { const v = n[k]; if (Array.isArray(v)) v.forEach((c) => walk(c, n, k)); else if (v && typeof v.type === 'string') walk(v, n, k); }
  };
  walk(ast, null, null);
  return [...refs].filter((r) => !decl.has(r));
}
const free = freeIds(utils + '\n' + body);
const threeAliases = free.filter((a) => alias.has(a)).map((a) => [a, alias.get(a)]);
const provided = new Set(['Zn', 'bi', 'Fo', 'kn', 'zc', 'Mn', 'en']);
const missing = free.filter((a) => !alias.has(a) && !provided.has(a) && !(a in globalThis) && !['document', 'window', 'performance', 'navigator', 'requestAnimationFrame'].includes(a));
if (missing.length) throw new Error('unresolved identifiers: ' + missing.join(' '));
const rebrand = [
  ['"PAC-9"', '"K9"'],
  ['LONGSHORE ARMS WORKS  \\xB7  SALTLINE', 'NAM GA ARMS  \\xB7  GA CHIM DEPOT'],
  ['SN PA-004217', 'SN GC-019442'],
  ['PA-REG 44/7', 'GC-REG 19/42'],
  ['"HX-2 REFLEX"', '"RD-4 REFLEX"'],
];
for (const [a, b] of rebrand) {
  if (!body.includes(a)) throw new Error('rebrand anchor missing: ' + a);
  body = body.split(a).join(b);
}

const head = `// GENERATED by tools/port-sl-weapon.js — do not edit by hand; edit the tool or the adapter in js/weapon.js.
// Viewmodel rifle, gloved hands, markings, reflex sight, gun materials and controller ported from
// Saltline by Felix Rieseberg (claude.ai artifact BGY1SztrAYcJQHSsnHHGmp). All credit for this code goes to its author.
import * as THREE from '../../vendor/three.module.min.js';
import { SUN_DIR, SUN_COLOR, PALETTE } from '../sky.js';
const { ${threeAliases.map(([a, n]) => `${n}: ${a}`).join(', ')} } = THREE;
const Zn = (i, e, t) => Math.min(t, Math.max(e, i)), bi = (i, e, t) => i + (e - i) * t, Fo = (i) => Math.min(1, Math.max(0, i)), kn = (i, e, t, n) => e + (i - e) * Math.exp(-t * n);
const zc = 1;
const Mn = { dir: SUN_DIR, color: SUN_COLOR };
const en = { zenith: PALETTE.zen, horizon: PALETTE.hor, horizonAway: PALETTE.horAway, fog: PALETTE.fog };
`;
const tail = `
export { dm as createSaltlineWeapon, mi as GUN, Wv as GUN_WET };
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, head + utils + '\n' + body + '\n' + tail);
console.log('wrote', OUT, (head + utils + body).length, 'chars;', threeAliases.length, 'three aliases');
