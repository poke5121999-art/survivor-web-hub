// Generates js/sl/audio-sl.js from the beautified Saltline bundle: DSP kit, sound generators, impulse
// responses, voice pools, mixer (compressor, soft clip, ducking), music stems and the event table.
// Saltline is by Felix Rieseberg (claude.ai artifact BGY1SztrAYcJQHSsnHHGmp); code and numbers are kept.
// Usage: node tools/port-sl-audio.js [D:/ref-saltline-gh/work/game.pretty.js]
'use strict';
const fs = require('fs');
const path = require('path');
const SRC = process.argv[2] || 'D:/ref-saltline-gh/work/game.pretty.js';
const OUT = path.join(__dirname, '..', 'js', 'sl', 'audio-sl.js');
const lines = fs.readFileSync(SRC, 'utf8').split('\n').map((l) => l.replace(/\r$/, ''));
let body = lines.slice(41311 - 1, 44526).join('\n');
// Ga Chìm is an inland freight yard: no foghorn or gulls, the sea bed becomes faint flood-water lapping.
const retune = [
  ['fog: 14 + s() * 14,', 'fog: 1 / 0,'],
  ['gull: 5 + s() * 8,', 'gull: 1 / 0,'],
  ['Oe.sea.setGain(fe * (1 - .5 * P) * 1)', 'Oe.sea.setGain(fe * (1 - .5 * P) * .12)'],
];
for (const [a, b] of retune) { if (!body.includes(a)) throw new Error('retune anchor missing: ' + a); body = body.split(a).join(b); }
for (const anchor of ['function u_(i, e, t) {', 'async function c_(i) {', 'Go = {']) if (!body.includes(anchor)) throw new Error('anchor missing: ' + anchor);
const head = `// GENERATED by tools/port-sl-audio.js — do not edit by hand; edit the tool or the adapter in js/audio.js.
// Procedural audio engine ported from Saltline by Felix Rieseberg (claude.ai artifact BGY1SztrAYcJQHSsnHHGmp).
// All credit for this code goes to its author.
`;
const tail = `
export { c_ as createSaltlineAudio, Go as SOUNDS };
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, head + body + '\n' + tail);
console.log('wrote', OUT, body.length, 'chars');
