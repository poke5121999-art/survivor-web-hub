// Shared helpers for the Saltline port tools: read the beautified bundle, map minified three.js aliases
// back to their names, find free identifiers, apply anchored text replacements, write a module.
'use strict';
const fs = require('fs');
const path = require('path');
const acorn = require(process.env.ACORN || 'C:/Users/tamph/AppData/Roaming/npm/node_modules/@google/gemini-cli/node_modules/acorn');

function readBundle(src) {
  const lines = fs.readFileSync(src, 'utf8').split('\n').map((l) => l.replace(/\r$/, ''));
  const alias = new Map();
  for (const l of lines.slice(0, 800)) { const m = l.match(/^\s+([A-Za-z0-9_]+): \(\) => ([A-Za-z0-9_$]+),?$/); if (m) alias.set(m[2], m[1]); }
  return { lines, alias, slice: (a, b) => lines.slice(a - 1, b).join('\n') };
}

function freeIds(src) {
  const ast = acorn.parse('(async function(){\n' + src + '\n})', { ecmaVersion: 2022 });
  const decl = new Set(), refs = new Set();
  const pat = (p) => { if (!p) return; if (p.type === 'Identifier') decl.add(p.name); else if (p.type === 'ObjectPattern') p.properties.forEach((q) => pat(q.value || q.argument)); else if (p.type === 'ArrayPattern') p.elements.forEach(pat); else if (p.type === 'AssignmentPattern') pat(p.left); else if (p.type === 'RestElement') pat(p.argument); };
  const walk = (n, parent, key) => {
    if (!n || typeof n.type !== 'string') return;
    if (n.type === 'VariableDeclarator') pat(n.id);
    else if (/Function/.test(n.type)) { if (n.id) decl.add(n.id.name); n.params.forEach(pat); }
    else if (/^Class/.test(n.type) && n.id) decl.add(n.id.name);
    else if (n.type === 'CatchClause') pat(n.param);
    else if (n.type === 'Identifier') {
      const isProp = parent && ((parent.type === 'MemberExpression' && key === 'property' && !parent.computed) || (/Property|MethodDefinition/.test(parent.type) && key === 'key' && !parent.computed && !parent.shorthand));
      if (!isProp) refs.add(n.name);
    }
    for (const k of Object.keys(n)) { const v = n[k]; if (Array.isArray(v)) v.forEach((c) => walk(c, n, k)); else if (v && typeof v.type === 'string') walk(v, n, k); }
  };
  walk(ast, null, null);
  return [...refs].filter((r) => !decl.has(r));
}

function replaceAll(body, pairs, label) {
  for (const [a, b] of pairs) {
    if (!body.includes(a)) throw new Error(`${label} anchor missing: ${a.slice(0, 80)}`);
    body = body.split(a).join(b);
  }
  return body;
}

// replace a top-level "function NAME(" through the line before the next top-level declaration
function replaceFunction(body, name, code) {
  const start = body.indexOf(`  function ${name}(`);
  if (start < 0) throw new Error('function missing: ' + name);
  const rest = body.slice(start + 1);
  const m = rest.match(/\n {2}(?:var|function|async function|let|const) /);
  const end = m ? start + 1 + m.index + 1 : body.length;
  return body.slice(0, start) + code + '\n' + body.slice(end);
}

function writeModule({ out, credit, imports, provided, code, exportsLine, alias }) {
  const free = freeIds(code);
  const threeAliases = free.filter((a) => alias.has(a) && !provided.has(a)).map((a) => [a, alias.get(a)]);
  const missing = free.filter((a) => !alias.has(a) && !provided.has(a) && !(a in globalThis) && !['document', 'window', 'performance', 'navigator', 'requestAnimationFrame'].includes(a));
  if (missing.length) throw new Error('unresolved identifiers: ' + missing.join(' '));
  const head = `// GENERATED by ${credit.tool} — do not edit by hand.
// Ported from Saltline by Felix Rieseberg (claude.ai artifact BGY1SztrAYcJQHSsnHHGmp). All credit for this code goes to its author.
${imports}
const { ${threeAliases.map(([a, n]) => `${n}: ${a}`).join(', ')} } = THREE;
`;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, head + code + '\n' + exportsLine + '\n');
  return { chars: code.length, aliases: threeAliases.length };
}

module.exports = { readBundle, freeIds, replaceAll, replaceFunction, writeModule };
