# -*- coding: utf-8 -*-
"""Nén lại art thẻ và art gặp gỡ của web cho nhẹ, từ ảnh PNG gốc (D:\\bazaar-ref\\art), ghi đè đúng đường dẫn art/ đang dùng.

Đo 2026-10-23 (1600×900 và điện thoại 844×390 DPR 2): ô art thẻ hiển thị tối đa ~300 px thiết bị, chân dung gặp gỡ ~165 px,
trong khi art.py --web xuất 512 px. Khung to hơn (tooltip ghim, sảnh, khung zoom) đã có BZHires đổi sang bản gốc 1024 px
(kho cho-phien-assets), nên bản cục bộ chỉ cần phủ cỡ hiển thị thường. Ngưỡng đổi của BZHires (js/view/hires.js LOCAL_PX)
phải bằng SIZE bên dưới.

Không gọi art.py --web: lệnh đó xoá cả art/ui, art/board... rồi dựng lại, mất các tệp do tool khác ghi vào đó.

Cũng ghi data/thumbs.js: bản 32 px (webp, data URI) của mọi art thẻ / gặp gỡ / kỹ năng / bước, một request lúc màn tải. Ô art hiện
ngay bản mờ này rồi rõ dần khi bản thật về (BZHires.paint) — chủ dự án chọn "mới load thì mờ, sau đó rõ dần" thay vì chờ tải hết art.

Chạy lại:  py -3.12 -I games/bazaar/tools/shrink_art.py [--dry]
"""
import base64
import io
import json
import os
import sys
import time
from concurrent.futures import ThreadPoolExecutor

from PIL import Image

sys.stdout.reconfigure(encoding="utf-8")
REF = r"D:\bazaar-ref"
ART = os.path.join(REF, "art")
MANIFEST = os.path.join(REF, "cache", "art_manifest.json")
WEB_ART = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "art"))

# nhóm -> (cạnh lớn nhất theo chiều cao, chất lượng webp, chế độ màu); RGB cho thẻ vì alpha của art thẻ là mặt nạ FX của shader
SIZE = {"cards": 320, "encounters": 256}
JOBS = {"cards": [("", 78, "RGB")], "encounters": [("_char", 80, "RGBA"), ("_bg", 72, "RGB")]}
THUMB_PX, THUMB_Q = 32, 50
THUMB_DIRS = ["cards", "encounters", "skills", "steps"]


def thumbs():
    out = {}
    for d in THUMB_DIRS:
        base = os.path.join(WEB_ART, d)
        for f in sorted(os.listdir(base)):
            if not f.endswith(".webp"):
                continue
            im = Image.open(os.path.join(base, f))
            im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
            k = float(THUMB_PX) / max(im.size)
            im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
            b = io.BytesIO()
            im.save(b, "WEBP", quality=THUMB_Q, method=6)
            out["art/" + d + "/" + f] = "data:image/webp;base64," + base64.b64encode(b.getvalue()).decode("ascii")
    js = ("/* generated by games/bazaar/tools/shrink_art.py - do not edit. Bản %d px của art thẻ / gặp gỡ / kỹ năng / bước, hiện mờ trong lúc bản thật tải */\n"
          "window.BZ_THUMBS=%s;\n" % (THUMB_PX, json.dumps(out, separators=(",", ":"))))
    p = os.path.join(WEB_ART, "..", "data", "thumbs.js")
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(js)
    print("thumbs.js: %d ảnh, %.0f KB" % (len(out), len(js) / 1024))


def encode(job):
    sp, dp, size, q, mode = job
    im = Image.open(sp).convert(mode)
    k = float(size) / im.height
    if k < 1:
        im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
    b = io.BytesIO()
    im.save(b, "WEBP", quality=q, method=4)
    for i in range(20):  # trên máy này mở tệp để ghi đôi lúc trả EINVAL vài trăm ms (tệp vừa bị tiến trình khác chạm vào): thử lại
        try:
            with open(dp, "wb") as fh:
                fh.write(b.getvalue())
            return len(b.getvalue())
        except OSError:
            time.sleep(0.25)
    raise OSError("không ghi được " + dp)


def main():
    dry = "--dry" in sys.argv
    manifest = json.load(open(MANIFEST, encoding="utf-8"))
    before = miss = 0
    seen, jobs = set(), []
    for m in manifest.values():
        cat = m["cat"]
        if cat not in JOBS:
            continue
        out = m["out"]
        for suf, q, mode in JOBS[cat]:
            src = out + suf + ".png" if cat == "encounters" else out
            dest = (out[:-4] if cat == "cards" else out) + suf + ".webp"
            dp = os.path.join(WEB_ART, dest.replace("/", os.sep))
            sp = os.path.join(ART, src.replace("/", os.sep))
            if dest in seen or not os.path.exists(dp):
                continue
            seen.add(dest)
            if not os.path.exists(sp):
                miss += 1
                continue
            before += os.path.getsize(dp)
            jobs.append((sp, dp, SIZE[cat], q, mode))
    after = 0
    if not dry:
        with ThreadPoolExecutor(max_workers=6) as ex:  # Pillow nhả GIL lúc nén; 6 luồng, máy chung
            after = sum(ex.map(encode, jobs))
    print("%d ảnh, %d thiếu nguồn; %.1f MB -> %.1f MB" % (len(jobs), miss, before / 1e6, after / 1e6))
    if not dry:
        thumbs()


if __name__ == "__main__":
    main()
