# -*- coding: utf-8 -*-
"""Ghi data/preload.js: danh sách ảnh giao diện lõi mà JS gắn vào lúc chạy (không nằm trong CSS nên màn tải không tự thấy):
nền bàn, khung thẻ 2D, lều / xe / orb / token của làn, thảm làn, VFX. Màn tải (js/ui/core.js bootPreload) chờ đủ các ảnh này cộng
ảnh trong CSS trước khi vào sảnh. Art thẻ / gặp gỡ không ở đây: chúng hiện bản mờ từ data/thumbs.js rồi rõ dần.

Chạy lại sau khi đổi các thư mục dưới:  py -3.12 -I games/bazaar/tools/preload_list.py
"""
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")

GAME = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DIRS = ["art/env", "art/frames2d", "art/ui/stall", "art/board/carpets", "art/board/board_common", "art/vfx"]


def main():
    out, size = [], 0
    for d in DIRS:
        for root, _, fs in os.walk(os.path.join(GAME, d)):
            for f in sorted(fs):
                if f.endswith((".webp", ".png", ".jpg")):
                    p = os.path.join(root, f)
                    out.append(os.path.relpath(p, GAME).replace("\\", "/"))
                    size += os.path.getsize(p)
    out.sort()
    with open(os.path.join(GAME, "data", "preload.js"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* generated by games/bazaar/tools/preload_list.py - do not edit. Ảnh giao diện lõi màn tải phải chờ (%d ảnh, %.1f MB) */\n"
                 "window.BZ_PRELOAD=%s;\n" % (len(out), size / 1e6, json.dumps(out, separators=(",", ":"))))
    print("preload.js: %d ảnh, %.1f MB" % (len(out), size / 1e6))


if __name__ == "__main__":
    main()
